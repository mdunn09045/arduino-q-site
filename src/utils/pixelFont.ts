// Convert string into a continuous bitmap strip
export function textToBitmapStrip(text: string): { width: number; height: number; data: number[][] } {
  const upper = text.toUpperCase().trim();
  const height = 5;
  const rows: number[][] = Array.from({ length: height }, () => []);

  for (let i = 0; i < upper.length; i++) {
    const char = upper[i];
    const glyph = FONT_3X5[char] || FONT_3X5[' '];

    const glyphWidth = glyph[0].length;
    for (let r = 0; r < height; r++) {
      for (let c = 0; c < glyphWidth; c++) {
        rows[r].push(glyph[r][c]);
      }
      // Add 1-column spacing between characters
      rows[r].push(0);
    }
  }

  const width = rows[0].length;
  return { width, height, data: rows };
}

// Generate smooth horizontal marquee scrolling frames for 13x8 Light Grid
export function renderScrollingNameFrames(
  text: string,
  cols = 13,
  rows = 8
): { matrix: number[][] }[] {
  const clean = text.toUpperCase().trim() || 'ADA';
  const strip = textToBitmapStrip(clean);

  // We want text to scroll in from the right edge, traverse across, and exit left
  // Total scroll steps = strip.width + cols
  const frames: { matrix: number[][] }[] = [];
  const topPad = Math.floor((rows - strip.height) / 2); // Center vertically (e.g. row 1 or 2)

  // Lead-in padding of blank columns
  const paddedStripWidth = strip.width + cols * 2;
  const fullStrip: number[][] = Array.from({ length: rows }, () => Array(paddedStripWidth).fill(0));

  for (let r = 0; r < strip.height; r++) {
    for (let c = 0; c < strip.width; c++) {
      fullStrip[topPad + r][cols + c] = strip.data[r][c];
    }
  }

  // Generate a frame for each pixel shift
  // Advance by 1 pixel each frame
  const totalFrames = strip.width + cols;
  for (let step = 0; step < totalFrames; step++) {
    const frameMatrix: number[][] = Array.from({ length: rows }, () => Array(cols).fill(0));
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        frameMatrix[r][c] = fullStrip[r][step + c];
      }
    }
    frames.push({ matrix: frameMatrix });
  }

  return frames;
}

// Generate letter-by-letter carousel frames (each letter centered on 13x8)
export function renderLetterCarouselFrames(
  text: string,
  cols = 13,
  rows = 8
): { matrix: number[][] }[] {
  const clean = text.toUpperCase().trim() || 'ADA';
  const frames: { matrix: number[][] }[] = [];

  for (let i = 0; i < clean.length; i++) {
    const char = clean[i];
    const glyph = FONT_3X5[char] || FONT_3X5[' '];
    const glyphW = glyph[0].length;
    const glyphH = glyph.length;

    const frameMatrix: number[][] = Array.from({ length: rows }, () => Array(cols).fill(0));
    const startR = Math.floor((rows - glyphH) / 2);
    const startC = Math.floor((cols - glyphW) / 2);

    for (let r = 0; r < glyphH; r++) {
      for (let c = 0; c < glyphW; c++) {
        frameMatrix[startR + r][startC + c] = glyph[r][c];
      }
    }

    // Add subtle corner accent dots to frame the letter
    frameMatrix[0][0] = 1;
    frameMatrix[0][cols - 1] = 1;
    frameMatrix[rows - 1][0] = 1;
    frameMatrix[rows - 1][cols - 1] = 1;

    frames.push({ matrix: frameMatrix });
  }

  return frames;
}
